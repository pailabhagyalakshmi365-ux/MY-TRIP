export function generateDayByDayItinerary(
  input: TripPlanFormInput,
  destination: Destination
): ItineraryDayPlan[] {
  const start = new Date(input.startDate || '2026-10-15');
  const end = new Date(input.endDate || '2026-10-18');
  const diffDays = Math.max(
    1,
    Math.min(10, Math.round((end.getTime() - start.getTime()) / (1000 * 60 * 60 * 24)) + 1)
  );

  const budgetMultiplier =
    input.budget === 'Budget' ? 0.75 : input.budget === 'Standard' ? 1.0 : input.budget === 'Premium' ? 1.45 : 2.1;

  const travelersCount = Math.max(1, input.adults + input.children * 0.6);
  const baseDailyCost = Math.round(
    (destination.costs.hotelPerNight +
      destination.costs.foodPerDay * travelersCount +
      destination.costs.localTransportPerDay +
      destination.costs.avgEntryTicket * travelersCount) *
      budgetMultiplier
  );

  const attractions = destination.famousAttractions;
  const things = destination.thingsToDo;
  const nearby = destination.nearbyPlaces;

  const days: ItineraryDayPlan[] = [];

  for (let i = 0; i < diffDays; i++) {
    const dayDate = new Date(start);
    dayDate.setDate(start.getDate() + i);
    const dateLabel = dayDate.toLocaleDateString('en-IN', {
      weekday: 'short',
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });

    if (i === 0) {
      const firstAttraction = attractions[0]?.name || `${destination.name} Heritage Core`;
      days.push({
        dayNumber: 1,
        dateLabel,
        title: `Day 1: Arrival in ${destination.name} & Welcome Exploration`,
        arrivalOrMorning: `Arrival from ${input.startingCity || 'Hyderabad'} via ${input.transportMode} · Airport/Station pickup & transfer`,
        hotelOrMidMorning: `Check-in at ${input.hotelPreference} in ${destination.name} & welcome refreshments`,
        lunch: `Authentic ${input.foodPreference} welcome lunch at a top-rated local restaurant in ${destination.name}`,
        afternoonAttraction: `Nearby sightseeing: Guided visit to ${firstAttraction} (${attractions[0]?.openingHours || '09:00 AM – 05:30 PM'})`,
        eveningActivity: things[0] || `Sunset promenade and cultural evening walk in ${destination.name}`,
        dinnerAndStay: `Signature regional dinner (${input.foodPreference}) & overnight stay in ${destination.name}`,
        estimatedDayCost: Math.round(baseDailyCost * 1.15),
      });
    } else if (i === diffDays - 1 && diffDays > 2 && nearby.length > 0) {
      const nearSpot = nearby[0];
      days.push({
        dayNumber: i + 1,
        dateLabel,
        title: `Day ${i + 1}: Excursion to ${nearSpot.name} & Souvenir Shopping`,
        arrivalOrMorning: `Early breakfast & scenic ${nearSpot.distanceKm} km drive to ${nearSpot.name} (${nearSpot.highlight})`,
        hotelOrMidMorning: `Explore viewpoints, heritage shrines, and photo stops around ${nearSpot.name}`,
        lunch: `Traditional ${input.foodPreference} thali meal en route with local specialties`,
        afternoonAttraction:
          things[i % things.length] || `Handloom & souvenir shopping in ${destination.name} craft markets`,
        eveningActivity: `Farewell sunset views, packing, and transfer for return ${input.transportMode} to ${input.startingCity}`,
        dinnerAndStay: `Farewell dinner & checkout / onward journey`,
        estimatedDayCost: Math.round(baseDailyCost * 0.95),
      });
    } else {
      const morningSpot = attractions[i % attractions.length] || attractions[0];
      const afternoonSpot = attractions[(i + 1) % attractions.length] || attractions[0];
      const eveningItem = things[i % things.length] || things[0];

      days.push({
        dayNumber: i + 1,
        dateLabel,
        title: `Day ${i + 1}: ${destination.name} Landmarks & ${input.interests[0] || 'Cultural'} Immersion`,
        arrivalOrMorning: `Morning attraction: ${morningSpot ? `${morningSpot.name} (${morningSpot.openingHours})` : destination.tagline}`,
        hotelOrMidMorning: `Interactive guided walk & photography session (${morningSpot?.timeRequired || '2.5 Hours'})`,
        lunch: `Mid-day meal featuring ${input.foodPreference} delicacies at a heritage dining spot`,
        afternoonAttraction: `Afternoon attraction: ${
          afternoonSpot && afternoonSpot.id !== morningSpot?.id
            ? `${afternoonSpot.name} — ${afternoonSpot.description}`
            : `Local museum & craft bazaar exploration in ${destination.name}`
        }`,
        eveningActivity: `Evening activity: ${eveningItem}`,
        dinnerAndStay: `Relaxed dinner & overnight stay at ${input.hotelPreference} in ${destination.name}`,
        estimatedDayCost: baseDailyCost,
      });
    }
  }

  return days;
}
